package net.uch.academica.jsf.beans;

/**
 * @author richard
 */
public class BeanDuplicadoHorario {

    private int dupId;
    private String dupHora;
    private String dupDia;
    private String dupNombreCurso;
    private String dupNombreCursos;

    public int getDupId() {
        return dupId;
    }

    public void setDupId(int dupId) {
        this.dupId = dupId;
    }

    public String getDupHora() {
        return dupHora;
    }

    public void setDupHora(String dupHora) {
        this.dupHora = dupHora;
    }

    public String getDupDia() {
        return dupDia;
    }

    public void setDupDia(String dupDia) {
        this.dupDia = dupDia;
    }

    public String getDupNombreCurso() {
        return dupNombreCurso;
    }

    public void setDupNombreCurso(String dupNombreCurso) {
        this.dupNombreCurso = dupNombreCurso;
    }

    public String getDupNombreCursos() {
        return dupNombreCursos;
    }

    public void setDupNombreCursos(String dupNombreCursos) {
        this.dupNombreCursos = dupNombreCursos;
    }
}
